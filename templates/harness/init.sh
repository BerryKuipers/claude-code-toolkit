#!/bin/bash
# Autonomous Coding Harness - Initialization Script
# This script initializes the harness for a new autonomous coding session

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="${PROJECT_ROOT:-$(pwd)}"
HARNESS_DIR="${PROJECT_ROOT}/.claude/harness"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

echo -e "${BLUE}=== Autonomous Coding Harness Initialization ===${NC}"

# Create harness directory structure
mkdir -p "$HARNESS_DIR"

# Initialize or validate feature_list.json
FEATURE_LIST="${HARNESS_DIR}/feature_list.json"
if [ ! -f "$FEATURE_LIST" ]; then
    echo -e "${YELLOW}Creating feature_list.json...${NC}"
    if [ -f "${SCRIPT_DIR}/feature_list.json" ]; then
        cp "${SCRIPT_DIR}/feature_list.json" "$FEATURE_LIST"
    else
        cat > "$FEATURE_LIST" << 'EOF'
{
  "project": {
    "name": "Unnamed Project",
    "description": "Project description"
  },
  "features": [],
  "metadata": {
    "version": "1.0.0",
    "created_at": "TIMESTAMP",
    "updated_at": "TIMESTAMP",
    "total_features": 0,
    "completed_features": 0
  }
}
EOF
    fi
    # Update timestamp
    if command -v jq &> /dev/null; then
        TIMESTAMP=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
        jq --arg ts "$TIMESTAMP" '.metadata.created_at = $ts | .metadata.updated_at = $ts' "$FEATURE_LIST" > "${FEATURE_LIST}.tmp" && mv "${FEATURE_LIST}.tmp" "$FEATURE_LIST"
    fi
    echo -e "${GREEN}Created: $FEATURE_LIST${NC}"
else
    echo -e "${GREEN}Found existing: $FEATURE_LIST${NC}"
fi

# Initialize or reset progress file
PROGRESS_FILE="${HARNESS_DIR}/claude-progress.txt"
echo -e "${YELLOW}Initializing progress file...${NC}"
cat > "$PROGRESS_FILE" << EOF
# Claude Progress Log
# Auto-generated by autonomous-coding harness

================================================================================
SESSION START
================================================================================
Started: $(date -u +"%Y-%m-%dT%H:%M:%SZ")
Mode: autonomous-coding
Feature List: ./feature_list.json

================================================================================
CURRENT STATUS
================================================================================
Active Feature: None
Overall Progress: 0/0 features completed

================================================================================
SESSION LOG
================================================================================
$(date -u +"%Y-%m-%dT%H:%M:%SZ") - Harness initialized

EOF
echo -e "${GREEN}Created: $PROGRESS_FILE${NC}"

# Initialize app_spec.txt if not exists
APP_SPEC="${HARNESS_DIR}/app_spec.txt"
if [ ! -f "$APP_SPEC" ]; then
    echo -e "${YELLOW}Creating app_spec.txt template...${NC}"
    if [ -f "${SCRIPT_DIR}/app_spec.txt" ]; then
        cp "${SCRIPT_DIR}/app_spec.txt" "$APP_SPEC"
    else
        cat > "$APP_SPEC" << 'EOF'
# Application Specification
# Edit this file to describe your application

================================================================================
PROJECT OVERVIEW
================================================================================
Name: [Your Project Name]
Type: [web-app | cli | library | api | mobile | other]
Language: [Primary language/framework]

================================================================================
ARCHITECTURE
================================================================================
[Describe your project's architecture here]

================================================================================
CONVENTIONS
================================================================================
[List your coding conventions]

================================================================================
CONSTRAINTS
================================================================================
[List any constraints to respect]
EOF
    fi
    echo -e "${GREEN}Created: $APP_SPEC${NC}"
else
    echo -e "${GREEN}Found existing: $APP_SPEC${NC}"
fi

# Copy schema if available
SCHEMA="${SCRIPT_DIR}/feature_list.schema.json"
if [ -f "$SCHEMA" ]; then
    cp "$SCHEMA" "${HARNESS_DIR}/"
    echo -e "${GREEN}Copied schema to harness directory${NC}"
fi

# Summary
echo ""
echo -e "${BLUE}=== Harness Ready ===${NC}"
echo -e "Harness directory: ${GREEN}${HARNESS_DIR}${NC}"
echo ""
echo "Files:"
ls -la "$HARNESS_DIR"
echo ""
echo -e "${YELLOW}Next steps:${NC}"
echo "1. Edit ${HARNESS_DIR}/app_spec.txt to describe your project"
echo "2. Edit ${HARNESS_DIR}/feature_list.json to define features"
echo "3. Run Claude with: claude --harness ${HARNESS_DIR}"
echo ""
